import "dotenv/config";import express from "express";import cors from "cors";
import helmet from "helmet";import path from "node:path";
import authRoutes from "./routes/auth.js";
import pageRoutes from "./routes/pages.js";
import blogRoutes from "./routes/blogs.js";
import leadRoutes from "./routes/leads.js";
import uploadRoutes from "./routes/uploads.js";
import publicRoutes from "./routes/public.js";
const app=express();
const origins=(process.env.CORS_ORIGINS??"http://localhost:3001,http://localhost:3000").split(",").map(v=>v.trim());
app.use(helmet({crossOriginResourcePolicy:{policy:"cross-origin"}}));
app.use(cors({origin:(origin,cb)=>{if(!origin||origins.includes(origin))return cb(null,true);
return cb(new Error("Origin not allowed by CORS"));
}}));
app.use(express.json({limit:"5mb"}));
app.use("/uploads",express.static(path.resolve(process.env.UPLOAD_DIR || "uploads")));
app.get("/health",(_req,res)=>res.json({status:"ok",service:"fundastra-admin-api"}));
app.use("/api/public",publicRoutes);
app.use("/api/auth",authRoutes);
app.use("/api/pages",pageRoutes);
app.use("/api/blogs",blogRoutes);
app.use("/api/leads",leadRoutes);
app.use("/api/uploads",uploadRoutes);
app.use((err:Error,_req:express.Request,res:express.Response,_next:express.NextFunction)=>{
console.error(err.message);
res.status(500).json({message:"Something went wrong on the server"});
});
const port=Number(process.env.PORT??4000);
app.listen(port, process.env.HOST || "0.0.0.0", ()=>console.log(`Fund Astra API listening on port ${port}`));
